"""Pull fm1-base's own SysEx routing code out of its sources, verbatim, into OUT/fm1_extract.c.

    extract.py [--base FM1_BASE] [--out DIR]
        FM1_BASE: fm1-base's tree (default: the reference/fm1-base found above this file); DIR: where fm1_extract.c and
        provenance.json go (default: instrument/build/sounds_ring/gen, never the source tree). run_all.sh's
        sounds_ring step passes both. harness.c #includes "gen/fm1_extract.c", so DIR's parent goes on the -I path.

Nothing here is re-typed: every function body below is copied from reference/fm1-base at test time, with a #line
directive so a compiler message points at the original file and line, and a sha256 of the text so the report can
name exactly what was tested. If fm1-base changes, this re-extracts the new code (or fails loudly when a marker is
gone).

  usb.c       sysex_byte, midi_in_event (the ISR's SysEx assembly and the two 6-byte keys), the frame slot and the
              TX ring (ota_wire_send, ota_frame_get, ota_frame_done), and their state declarations
  main_fm1.c  remote_frame, usb_cmd, log_frame's accept test, and the main loop's dispatch block (the chain
              ann_frame || log_frame || remote_frame [|| app_sysex], ota_service/usb_cmd, the ota/uboot requests)
  unity.c     ann_wire_send (the device's non-blocking send that app_sounds.c uses on the device)
  plat_fm1.c  the remote-control state
  backup.c    the request ids and error codes usb_cmd uses
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP = HERE.parent.parent.parent                  # (tests/sounds/ring -> instrument)


def find_base():
    for d in [APP, *APP.parents]:
        if (d / "reference" / "fm1-base").is_dir():
            return d / "reference" / "fm1-base"
    return APP.parent / "reference" / "fm1-base"


_ap = argparse.ArgumentParser(description="extract fm1-base's SysEx routing code verbatim for harness.c")
_ap.add_argument("--base", type=Path, default=None, help="fm1-base's tree (default: reference/fm1-base above this file)")
_ap.add_argument("--out", type=Path, default=APP / "build" / "sounds_ring" / "gen", help="where fm1_extract.c goes")
_args = _ap.parse_args()
BASE = (_args.base or find_base()).resolve()
if not (BASE / "bsp" / "chip" / "usb.c").is_file():
    sys.exit(f"extract: {BASE} is not fm1-base (no bsp/chip/usb.c)")
OUT = _args.out.resolve() / "fm1_extract.c"
PROV = _args.out.resolve() / "provenance.json"

prov = []


def lines_of(rel):
    return (BASE / rel).read_text().split("\n")


def emit(rel, start, end, text, what):
    h = hashlib.sha256(text.encode()).hexdigest()
    prov.append({"what": what, "file": f"reference/fm1-base/{rel}", "lines": [start + 1, end + 1], "sha256": h})
    return f"/* ---- EXTRACTED VERBATIM: {what} = reference/fm1-base/{rel}:{start + 1}-{end + 1} sha256 {h[:16]} */\n" \
           f'#line {start + 1} "{BASE / rel}"\n{text}\n'


def func(rel, sig, what=None):
    """a function from its signature line (regex, at the line's start) to the first '}' alone in column 0"""
    L = lines_of(rel)
    for i, s in enumerate(L):
        if re.match(sig, s):
            for j in range(i, len(L)):
                if L[j] == "}":
                    return emit(rel, i, j, "\n".join(L[i:j + 1]), what or sig)
            break
    sys.exit(f"extract: {sig!r} not found in {rel}")


def span(rel, first, last, what):
    """the lines from the first containing `first` to the next containing `last`, inclusive"""
    L = lines_of(rel)
    for i, s in enumerate(L):
        if first in s:
            for j in range(i, len(L)):
                if last in L[j]:
                    return emit(rel, i, j, "\n".join(L[i:j + 1]), what), "\n".join(L[i:j + 1])
            break
    sys.exit(f"extract: span {first!r}..{last!r} not found in {rel}")


def line(rel, pat, what):
    L = lines_of(rel)
    for i, s in enumerate(L):
        if re.search(pat, s):
            return emit(rel, i, i, s, what), s
    sys.exit(f"extract: {pat!r} not found in {rel}")


parts = ["/* GENERATED by extract.py from reference/fm1-base: do not edit. */\n"]

# ---- usb.c: the receive slot and TX ring state, the ISR's assembly, the main loop's slot calls, the TX ring
parts.append(span("bsp/chip/usb.c", "static uint8_t sx_frame[640];", "static volatile uint32_t so_w, so_r;",
                  "usb.c SysEx slot + TX ring state")[0])
parts.append(func("bsp/chip/usb.c", r"static void sysex_byte\(uint8_t b\)", "usb.c sysex_byte"))
parts.append(func("bsp/chip/usb.c", r"static void midi_in_event\(uint32_t pkt\)", "usb.c midi_in_event"))
parts.append(func("bsp/chip/usb.c", r"static int ota_wire_send\(", "usb.c ota_wire_send"))
parts.append(func("bsp/chip/usb.c", r"static int ota_frame_get\(", "usb.c ota_frame_get"))
parts.append(func("bsp/chip/usb.c", r"static void ota_frame_done\(void\)", "usb.c ota_frame_done"))

# ---- ota.c: whole (it is the portable core: the Mac test builds it too)
parts.append(f'/* ---- ota.c, whole */\n#line 1 "{BASE / "bsp/chip/ota.c"}"\n#include "{BASE / "bsp/chip/ota.c"}"\n')
prov.append({"what": "ota.c (whole file, #included)", "file": "reference/fm1-base/bsp/chip/ota.c",
             "sha256": hashlib.sha256((BASE / "bsp/chip/ota.c").read_bytes()).hexdigest()})

# ---- backup.c: the ids and codes usb_cmd needs
for pat in (r"^#define RS_REQ ", r"^#define BU_REQ ", r"^#define BU_END ", r"^#define BU_MAGIC "):
    parts.append(line("device/backup.c", pat, "backup.c " + pat.strip("^#define ").strip())[0])
parts.append(span("device/backup.c", "enum { RS_E_SIZE = 1", "RS_E_PLAYING, RS_E_NO, RS_E_COMMIT };",
                  "backup.c RS_E_* codes")[0])
for pat in (r"^#define BU_HEAD ", r"^#define BU_CHUNK ", r"^#define BU_STALL_MS "):
    parts.append(line("device/backup.c", pat, "backup.c " + pat.strip("^#define ").strip())[0])
# the backup's own state and its start / stop / frame (the stream's body, bu_next, reads storage.c: modelled)
parts.append("static int bu_room(void);\nstatic int bu_send(const uint8_t *p, uint32_t n);\n"
             "static void bu_flush(void);\nstatic void bu_hold(int on);\n")
parts.append(span("device/backup.c", "static uint32_t bu_rd16(const uint8_t *p)", "static void bu_wr32(uint8_t *p, uint32_t v)",
                  "backup.c byte helpers")[0])
parts.append(span("device/backup.c", "enum { BU_S_HEAD, BU_S_REC, BU_S_BODY, BU_S_TAIL, BU_S_END };", "} bu;",
                  "backup.c bu state")[0])
parts.append(line("device/backup.c", r"^static uint8_t bu_msg\[", "backup.c bu_msg/bu_wire")[0])
parts.append(func("device/backup.c", r"static int bu_frame\(", "backup.c bu_frame"))
parts.append(func("device/backup.c", r"static void bu_start\(int playing\)", "backup.c bu_start"))
parts.append(func("device/backup.c", r"static void bu_stop\(void\)", "backup.c bu_stop"))

# ---- plat_fm1.c: the remote-control state the remote frames write (plat_buttons ORs remote.btn in)
parts.append(span("device/plat_fm1.c", "static struct {", "} remote = {0, 0, {0}, -1};",
                  "plat_fm1.c remote state")[0])

# ---- main_fm1.c: the platform's own handlers
parts.append(func("device/main_fm1.c", r"static int remote_frame\(", "main_fm1.c remote_frame"))
g, gl = line("device/main_fm1.c", r"p\[1\] != 0x4Cu \|\| p\[2\] != 0x47u\)", "main_fm1.c log_frame accept test")
parts.append("/* log_frame: its body reads crash records and power registers (hardware); its accept test is verbatim: */\n"
             "static int log_frame(const uint8_t *p, uint32_t n)\n{\n" + g +
             "        return 0;\n    hs_log_frame_taken();\n    return 1;\n}\n")
parts.append(func("device/main_fm1.c", r"static void usb_cmd\(uint32_t d\)", "main_fm1.c usb_cmd"))

# ---- the main loop's dispatch, twice: CYMA-1's build (APP_SYSEX) and the same platform without it (the baseline)
disp_emit, disp = span("device/main_fm1.c", "a screen reader's SysEx (announce.c), before the updater looks",
                       'enter_uboot("UBOOT (USB)");', "main_fm1.c main-loop dispatch block")
k = disp_emit.index("#line")
hdr, body = disp_emit[:k], disp_emit[k:]
parts.append('#include "dispatch_pre.h"\n')
parts.append(hdr)
parts.append("static void fm1_dispatch_with(void)\n{\n" + body + "}\n")
parts.append("#pragma push_macro(\"APP_SYSEX\")\n#undef APP_SYSEX\n")
parts.append("static void fm1_dispatch_without(void)\n{\n" + body + "}\n")
parts.append("#pragma pop_macro(\"APP_SYSEX\")\n")
parts.append('#include "dispatch_post.h"\n')

# ---- unity.c: the device's ann_wire_send (app_sounds.c's app_sx_send on the device), renamed only; the backup glue
parts.append("static uint8_t backup_streaming(void) { return bu.on; }   /* unity.c, FM1B_BACKUP */\n")
u_emit = func("device/unity.c", r"static int ann_wire_send\(const uint8_t \*p, uint32_t n\)", "unity.c ann_wire_send")
parts.append(u_emit.replace("static int ann_wire_send(const uint8_t *p, uint32_t n)",
                            "static int dev_ann_wire_send(const uint8_t *p, uint32_t n)", 1))
parts.append(func("device/unity.c", r"static int bu_room\(void\)", "unity.c bu_room"))
for pat, w in ((r"^static int bu_send\(", "unity.c bu_send"), (r"^static void bu_flush\(void\)", "unity.c bu_flush"),
               (r"^static void bu_hold\(int on\)", "unity.c bu_hold")):
    parts.append(line("device/unity.c", pat, w)[0])

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("".join(parts))
PROV.write_text(json.dumps(prov, indent=1))
print(f"extract: {len(prov)} pieces -> {OUT}")
for p in prov:
    print(f"  {p['what']:<40} {p['file']}:{'-'.join(map(str, p.get('lines', [])))} {p['sha256'][:16]}")
